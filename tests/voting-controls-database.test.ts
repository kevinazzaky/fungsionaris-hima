import assert from "node:assert/strict";
import test from "node:test";
import { readFile, readdir } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { PGlite } from "@electric-sql/pglite";

test("buka/tutup mempertahankan suara; reset atomik membuat backup, memulihkan hak, dan menolak sesi lama", async () => {
  const db = new PGlite();
  try {
    await db.exec("CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;");
    await db.exec("ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon,authenticated,service_role;");
    const migrations = (await readdir("prisma/migrations", { withFileTypes: true })).filter(entry => entry.isDirectory()).map(entry => entry.name).sort();
    for (const migration of migrations)
      await db.exec(await readFile(`prisma/migrations/${migration}/migration.sql`, "utf8"));
    const admin = randomUUID(), election = randomUUID(), candidate = randomUUID(), other = randomUUID(), otherCandidate = randomUUID();
    await db.query('INSERT INTO "AdminUser"(id,"authId",email) VALUES($1,$2,$3)', [admin, randomUUID(), "admin@voting.test"]);
    await db.query("INSERT INTO elections(id,period) VALUES($1,'2026/2027'),($2,'2027/2028')", [election, other]);
    await db.query("UPDATE voting_settings SET election_id=$1 WHERE id='main'", [election]);
    for (const [id, electionId] of [[candidate, election], [otherCandidate, other]]) {
      await db.query("INSERT INTO candidates(id,election_id,number,name,vision,missions,photo_path,placeholder) VALUES($1,$2,1,'Calon Uji','Visi pengujian',ARRAY['Misi pengujian'],'/brand/logo-emblem.png',false)", [id, electionId]);
      await db.query("INSERT INTO audit_logs(election_id,actor_id,action) VALUES($1,$2,'draft_created')", [electionId, admin]);
    }
    await db.query("INSERT INTO eligible_voters(election_id,voter_key,name,eligible) VALUES($1,'alpha','Pemilih Uji',true),($1,'beta','Pemilih Uji',true),($1,'inactive','Pemilih Uji',false),($2,'other','Pemilih Lain',true)", [election, other]);
    const open = (id: string) => db.query("UPDATE elections SET status='scheduled',starts_at=clock_timestamp()-interval '1 second',ends_at=clock_timestamp()+interval '1 hour' WHERE id=$1", [id]);
    const close = () => db.query("UPDATE elections SET status='closed' WHERE id=$1", [election]);
    const cast = async (key: string, version = 0) => (await db.query<{ accepted: boolean }>("SELECT cast_hima_ballot($1,$2,$3,$4) AS accepted", [election, key, candidate, version])).rows[0].accepted;
    const totals = async (id = election) => (await db.query<{ ballots: number; consumed: number; version: number; status: string }>("SELECT (SELECT count(*)::int FROM ballots WHERE election_id=$1) AS ballots,(SELECT count(*)::int FROM eligible_voters WHERE election_id=$1 AND consumed) AS consumed,token_version AS version,status FROM elections WHERE id=$1", [id])).rows[0];
    const reset = (actor = admin, confirmation = "RESET 2026/2027") => db.query<{ backup_id: string; ballots_removed: number; rights_restored: number; audit_action: string }>("SELECT * FROM reset_hima_voting_test_period($1,$2,$3)", [election, actor, confirmation]);
    await open(election);
    assert.equal(await cast("alpha"), true);
    await close();
    assert.equal(await cast("beta"), false);
    assert.deepEqual(await totals(), { ballots: 1, consumed: 1, version: 0, status: "closed" });
    await assert.rejects(db.query("UPDATE elections SET status='draft' WHERE id=$1", [election]), /locked/);
    await open(election);
    assert.equal(await cast("alpha"), false);
    assert.equal(await cast("beta"), true);
    await assert.rejects(db.query("UPDATE elections SET ends_at=ends_at+interval '1 hour' WHERE id=$1", [election]), /locked/);
    await assert.rejects(reset(), /voting_reset_requires_closed/);
    await close();
    await assert.rejects(reset(admin, "RESET 2027/2028"), /voting_reset_confirmation/);
    await assert.rejects(reset(randomUUID()), /voting_reset_admin/);
    await assert.rejects(db.query("DELETE FROM ballots WHERE election_id=$1", [election]), /immutable/);
    await assert.rejects(db.query("UPDATE eligible_voters SET consumed=false WHERE election_id=$1 AND consumed", [election]), /locked/);
    await open(other);
    assert.equal((await db.query<{ accepted: boolean }>("SELECT cast_hima_ballot($1,'other',$2) AS accepted", [other, otherCandidate])).rows[0].accepted, true);
    const otherBefore = await totals(other);
    const candidatesBefore = (await db.query("SELECT * FROM candidates WHERE election_id=$1 ORDER BY id", [election])).rows;
    const votersBefore = (await db.query<Record<string, unknown>>("SELECT * FROM eligible_voters WHERE election_id=$1 ORDER BY voter_key", [election])).rows;
    const auditBefore = (await db.query<Record<string, unknown>>("SELECT * FROM audit_logs WHERE election_id=$1 ORDER BY id", [election])).rows;
    await db.query("INSERT INTO voting_rate_limits(key,scope,expires_at) VALUES('nim:alpha','nim',now()+interval '5 minutes'),('cast:alpha','submit',now()+interval '5 minutes'),($1,'status',now()+interval '5 minutes'),('network:test','check',now()+interval '5 minutes'),('nim:other','nim',now()+interval '5 minutes')", [`status:${election}:alpha`]);
    await db.exec("BEGIN");
    await db.query("SELECT set_config('hima.voting_reset',$1,true)", [election]);
    await db.query("DELETE FROM ballots WHERE id=(SELECT id FROM ballots WHERE election_id=$1 LIMIT 1)", [election]);
    await db.query("SELECT set_config('hima.voting_reset','',true)");
    await assert.rejects(reset(), /voting_reset_audit_mismatch/);
    await db.exec("ROLLBACK");
    await db.exec("BEGIN");
    await reset();
    await db.exec("ROLLBACK");
    assert.deepEqual(await totals(), { ballots: 2, consumed: 2, version: 0, status: "closed" });
    assert.equal((await db.query<{ count: number }>("SELECT count(*)::int AS count FROM voting_reset_backups")).rows[0].count, 0);
    const result = (await reset()).rows[0];
    await assert.rejects(reset(), /voting_reset_requires_closed/);
    assert.equal(result.ballots_removed, 2);
    assert.equal(result.rights_restored, 2);
    assert.equal(result.audit_action, "test_period_reset_by_operator:user_requested;dummy_ballots_removed=2;rights_restored=2");
    assert.deepEqual(await totals(), { ballots: 0, consumed: 0, version: 1, status: "draft" });
    assert.equal((await db.query<{ election_id: string }>("SELECT election_id FROM voting_settings WHERE id='main'")).rows[0].election_id, election);
    assert.deepEqual(await totals(other), otherBefore);
    assert.deepEqual((await db.query("SELECT * FROM candidates WHERE election_id=$1 ORDER BY id", [election])).rows, candidatesBefore);
    assert.deepEqual((await db.query("SELECT * FROM eligible_voters WHERE election_id=$1 ORDER BY voter_key", [election])).rows, votersBefore.map(voter => ({ ...voter, consumed: false })));
    const auditAfter = (await db.query<Record<string, unknown>>("SELECT * FROM audit_logs WHERE election_id=$1 ORDER BY id", [election])).rows;
    assert.deepEqual(auditAfter.filter(row => row.action !== result.audit_action), auditBefore);
    assert.equal(auditAfter.length, auditBefore.length + 1);
    const backup = (await db.query<{ snapshot: { ballots: unknown[]; voters: unknown[]; candidates: unknown[]; election: { token_version: number } } }>("SELECT snapshot FROM voting_reset_backups WHERE id=$1", [result.backup_id])).rows[0].snapshot;
    assert.equal(backup.ballots.length, 2);
    assert.equal(backup.voters.length, 3);
    assert.equal(backup.candidates.length, 1);
    assert.equal(backup.election.token_version, 0);
    assert.deepEqual((await db.query<{ key: string }>("SELECT key FROM voting_rate_limits ORDER BY key")).rows.map(row => row.key), ["network:test", "nim:other"]);
    await assert.rejects(db.query("DELETE FROM voting_reset_backups"), /immutable/);
    await assert.rejects(db.query("DELETE FROM audit_logs"), /immutable/);
    for (const role of ["anon", "authenticated", "service_role"]) {
      await db.exec(`SET ROLE ${role}`);
      await assert.rejects(db.query("SELECT * FROM voting_reset_backups"), /permission denied/);
      await assert.rejects(reset(), /permission denied/);
      await db.exec("RESET ROLE");
    }
    await db.exec("SET ROLE authenticated");
    await db.query("SELECT set_config('hima.voting_reset',$1,false)", [election]);
    await assert.rejects(db.query("DELETE FROM ballots WHERE election_id=$1", [election]), /permission denied/);
    await db.exec("RESET ROLE");
    await db.exec("SET ROLE service_role");
    await db.query("SELECT set_config('hima.voting_reset',$1,false)", [other]);
    await assert.rejects(db.query("DELETE FROM ballots WHERE election_id=$1", [other]), /immutable/);
    await db.exec("RESET ROLE");
    await db.query("SELECT set_config('hima.voting_reset','',false)");
    await db.query("UPDATE elections SET status='scheduled',starts_at=clock_timestamp()-interval '2 hours',ends_at=clock_timestamp()-interval '1 hour' WHERE id=$1", [election]);
    await open(election);
    assert.equal(await cast("alpha", 0), false);
    assert.equal((await db.query<{ accepted: boolean }>("SELECT cast_hima_ballot($1,'alpha',$2) AS accepted", [election, candidate])).rows[0].accepted, false);
    assert.equal(await cast("alpha", 1), true);
    assert.equal(await cast("alpha", 1), false);
    assert.equal(await cast("inactive", 1), false);
    const protection = (await db.query<{ tgenabled: string }>("SELECT tgenabled FROM pg_trigger WHERE NOT tgisinternal")).rows;
    assert.ok(protection.every(trigger => trigger.tgenabled === "O"));
  } finally { await db.close(); }
});
